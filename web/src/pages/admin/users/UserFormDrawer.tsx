import { useMemo } from 'react'
import { Button, Col, Drawer, Form, Grid, Input, InputNumber, Row, Select, Space, Switch, TreeSelect } from 'antd'
import { useTranslation } from 'react-i18next'
import { applyFieldErrors } from '@/api/formErrors'
import { qk } from '@/api/queryKeys'
import { createUser, updateUser } from '@/api/users'
import { useApiMutation } from '@/hooks/useApiMutation'
import { useAllUserGroups, useOrgTree, usePasswordPolicy, useRoles } from '@/hooks/useLookups'
import type { SaveUserRequest, SaveUserResult, UserDto } from '@/types/admin'
import { GB } from '@/utils/format'
import { policyValidator } from '@/utils/passwordPolicy'
import { filterTreeNodeUnaccent, orgTreeToSelect } from '@/utils/tree'

const USERNAME_PATTERN = /^[a-zA-Z0-9._-]{3,50}$/
const PHONE_PATTERN = /^[0-9+()\s.-]{6,20}$/
const FIELDS = ['username', 'fullName', 'email', 'phone', 'organizationId', 'position', 'quotaGb', 'isActive', 'roleIds', 'groupIds', 'password']

interface UserFormDrawerProps {
  open: boolean
  editing: UserDto | null
  onClose: () => void
  /** Called after create with the temporary password generated by the server (if any). */
  onCreated?: (user: { username: string }, result: SaveUserResult) => void
}

interface UserFormValues {
  username: string
  fullName: string
  email?: string
  phone?: string
  organizationId?: string | null
  position?: string
  quotaGb?: number | null
  isActive: boolean
  roleIds: string[]
  groupIds: string[]
  password?: string
}

function UserForm({ editing, onClose, onCreated }: Omit<UserFormDrawerProps, 'open'>) {
  const { t } = useTranslation()
  const screens = Grid.useBreakpoint()
  const [form] = Form.useForm<UserFormValues>()
  const tree = useOrgTree()
  const roles = useRoles()
  const groups = useAllUserGroups()
  const policy = usePasswordPolicy()
  const treeData = useMemo(() => orgTreeToSelect(tree.data), [tree.data])

  const mutation = useApiMutation(
    (body: SaveUserRequest) => (editing ? updateUser(editing.id, body) : createUser(body)),
    {
      successMessage: editing ? t('user.updated') : t('user.created'),
      invalidate: [qk.users, qk.userGroups, qk.roles, qk.organizations],
      onSuccess: (result, body) => {
        onClose()
        if (!editing) onCreated?.({ username: body.username }, result)
      },
      onError: (error) => {
        applyFieldErrors(form, error, FIELDS)
      },
    },
  )

  const submit = (v: UserFormValues) =>
    mutation.mutate({
      username: v.username.trim(),
      fullName: v.fullName.trim(),
      email: v.email?.trim() || null,
      phone: v.phone?.trim() || null,
      organizationId: v.organizationId ?? null,
      position: v.position?.trim() || null,
      quotaGb: v.quotaGb ?? null,
      isActive: v.isActive,
      roleIds: v.roleIds ?? [],
      groupIds: v.groupIds ?? [],
      password: editing ? null : v.password || null,
    })

  const initialValues: Partial<UserFormValues> = editing
    ? {
        username: editing.username,
        fullName: editing.fullName,
        email: editing.email ?? undefined,
        phone: editing.phone ?? undefined,
        organizationId: editing.organizationId,
        position: editing.position ?? undefined,
        quotaGb: Math.round((editing.quotaBytes / GB) * 100) / 100,
        isActive: editing.isActive,
        roleIds: editing.roles.map((r) => r.id),
        groupIds: editing.groups.map((g) => g.id),
      }
    : { isActive: true, roleIds: [], groupIds: [] }

  return (
    <Drawer
      open
      title={editing ? t('user.editTitle', { name: editing.fullName }) : t('user.createTitle')}
      width={screens.md ? 640 : '100%'}
      onClose={onClose}
      destroyOnHidden
      extra={
        <Space>
          <Button onClick={onClose}>{t('common.cancel')}</Button>
          <Button type="primary" loading={mutation.isPending} onClick={() => form.submit()}>
            {t('common.save')}
          </Button>
        </Space>
      }
    >
      <Form<UserFormValues> form={form} layout="vertical" initialValues={initialValues} onFinish={submit}>
        <Row gutter={16}>
          <Col xs={24} sm={12}>
            <Form.Item
              name="username"
              label={t('user.username')}
              rules={[
                { required: true, whitespace: true, message: t('validation.usernameRequired') },
                { pattern: USERNAME_PATTERN, message: t('validation.usernamePattern') },
              ]}
            >
              <Input maxLength={50} autoComplete="off" disabled={editing?.username === 'admin'} />
            </Form.Item>
          </Col>
          <Col xs={24} sm={12}>
            <Form.Item
              name="fullName"
              label={t('user.fullName')}
              rules={[
                { required: true, whitespace: true, message: t('validation.fullNameRequired') },
                { max: 255, message: t('validation.maxLength', { max: 255 }) },
              ]}
            >
              <Input maxLength={255} />
            </Form.Item>
          </Col>
          <Col xs={24} sm={12}>
            <Form.Item name="email" label={t('user.email')} rules={[{ type: 'email', message: t('validation.emailInvalid') }]}>
              <Input maxLength={255} autoComplete="off" />
            </Form.Item>
          </Col>
          <Col xs={24} sm={12}>
            <Form.Item name="phone" label={t('user.phone')} rules={[{ pattern: PHONE_PATTERN, message: t('validation.phoneInvalid') }]}>
              <Input maxLength={20} />
            </Form.Item>
          </Col>
          <Col xs={24} sm={12}>
            <Form.Item name="organizationId" label={t('user.organization')}>
              <TreeSelect
                allowClear
                showSearch
                treeData={treeData}
                loading={tree.isLoading}
                placeholder={t('user.organizationPlaceholder')}
                filterTreeNode={filterTreeNodeUnaccent}
                treeDefaultExpandAll
                popupMatchSelectWidth={false}
              />
            </Form.Item>
          </Col>
          <Col xs={24} sm={12}>
            <Form.Item name="position" label={t('user.position')} rules={[{ max: 255, message: t('validation.maxLength', { max: 255 }) }]}>
              <Input maxLength={255} />
            </Form.Item>
          </Col>
          <Col xs={12}>
            <Form.Item name="quotaGb" label={t('user.quotaGb')} extra={t('user.quotaHint')}>
              <InputNumber min={0} max={100000} step={1} style={{ width: '100%' }} addonAfter="GB" />
            </Form.Item>
          </Col>
          <Col xs={12}>
            <Form.Item name="isActive" label={t('common.status')} valuePropName="checked">
              <Switch checkedChildren={t('status.active')} unCheckedChildren={t('status.inactive')} />
            </Form.Item>
          </Col>
          <Col xs={24}>
            <Form.Item name="roleIds" label={t('user.roles')}>
              <Select
                mode="multiple"
                allowClear
                optionFilterProp="label"
                loading={roles.isLoading}
                placeholder={t('user.rolesPlaceholder')}
                options={roles.data?.map((r) => ({ value: r.id, label: r.name }))}
              />
            </Form.Item>
          </Col>
          <Col xs={24}>
            <Form.Item name="groupIds" label={t('user.groups')}>
              <Select
                mode="multiple"
                allowClear
                optionFilterProp="label"
                loading={groups.isLoading}
                placeholder={t('user.groupsPlaceholder')}
                options={groups.data?.map((g) => ({ value: g.id, label: g.name }))}
              />
            </Form.Item>
          </Col>
          {!editing && (
            <Col xs={24}>
              <Form.Item
                name="password"
                label={t('user.initialPassword')}
                extra={t('user.initialPasswordHint')}
                rules={[{ validator: policyValidator(policy.data) }]}
              >
                <Input.Password maxLength={256} autoComplete="new-password" />
              </Form.Item>
            </Col>
          )}
        </Row>
      </Form>
    </Drawer>
  )
}

/** Create/edit user drawer (remounted on every open). */
export default function UserFormDrawer({ open, ...rest }: UserFormDrawerProps) {
  return open ? <UserForm {...rest} /> : null
}
